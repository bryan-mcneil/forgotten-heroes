#!/usr/bin/env python3
"""Generate the event catalogue of engine/README.md from the Javadoc one-liners in GameEvent.java.

    python tools/docs/event_catalog.py            # print the Markdown table
    python tools/docs/event_catalog.py --write    # rewrite the block between the markers in engine/README.md
    python tools/docs/event_catalog.py --check    # exit 1 when the README block is stale (for CI)

The README is the frontend's reference; generating it from the source means the two can never drift.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "engine/src/main/java/com/forgottenheroes/engine/event/GameEvent.java"
README = ROOT / "engine/README.md"
START = "<!-- events:start (generated by tools/docs/event_catalog.py; do not edit by hand) -->"
END = "<!-- events:end -->"

# one-line Javadoc, then the record header, possibly wrapped over several lines
RECORD = re.compile(r"/\*\*(?P<doc>[^\n]*?)\*/\s*record\s+(?P<name>\w+)\((?P<fields>.*?)\)\s*implements\s+GameEvent", re.DOTALL)
SECTION = re.compile(r"// ----- (?P<title>[^-]+?) -+")


def catalogue(source: str) -> str:
    rows = []
    section = ""
    sections = [(m.start(), m.group("title").strip()) for m in SECTION.finditer(source)]
    for match in RECORD.finditer(source):
        while sections and sections[0][0] < match.start():
            section = sections.pop(0)[1]
        fields = []
        for part in match.group("fields").replace("\n", " ").split(","):
            name = part.strip().split()[-1] if part.strip() else ""
            if name and name != "seq":
                fields.append(f"`{name}`")
        doc = " ".join(match.group("doc").split()).replace("{@code ", "`").replace("}", "`")
        rows.append((section, match.group("name"), ", ".join(fields), doc))
    lines = ["| Event | Fields (besides `seq` and `type`) | Meaning |", "|---|---|---|"]
    current = None
    for section, name, fields, doc in rows:
        if section != current:
            lines.append(f"| **{section}** | | |")
            current = section
        lines.append(f"| `{name}` | {fields} | {doc} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    table = catalogue(SOURCE.read_text(encoding="utf-8"))
    if "--write" in sys.argv or "--check" in sys.argv:
        readme = README.read_text(encoding="utf-8")
        start, end = readme.index(START), readme.index(END)
        updated = readme[: start + len(START)] + "\n" + table + readme[end:]
        if "--check" in sys.argv:
            if updated != readme:
                print("engine/README.md event catalogue is stale: run python tools/docs/event_catalog.py --write")
                return 1
            print("engine/README.md event catalogue is up to date")
            return 0
        README.write_text(updated, encoding="utf-8", newline="\n")
        print(f"engine/README.md updated ({table.count(chr(10)) - 2} rows)")
        return 0
    print(table, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
